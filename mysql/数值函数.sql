



-- round、ceil函数
select round(1.1 / 1),
       round(0.4 / 1),
       round(-0.4 / 1),
       round(-1.4 / 1),
       ceil(1.1 / 1),
       ceil(0.4 / 1),
       ceil(-0.4 / 1),
       ceil(-1.4 / 1),
       floor(1.1 / 1),
       floor(0.4 / 1),
       floor(-0.4 / 1),
       floor(-1.4 / 1)
from dual;

